const _seededKey = 'news_library_v1_seeded';

/// 뉴스 원고 묶음을 분야별 폴더에 한 번만 넣는다. 같은 이름의 폴더가 있으면 그 폴더를 쓴다.
/// 사용자가 지운 원고는 다시 넣지 않는다.
Future<void> seedNewsLibrary(
    Database db, ScriptRepository scripts, FolderRepository folders) async {
  final done = await db.query('settings', where: 'key = ?', whereArgs: [_seededKey]);
  if (done.isNotEmpty) return;

  final existing = {for (final f in await folders.all()) f.name: f.id!};
  final folderIds = <String, int>{};
  for (final c in newsCategories) {
    folderIds[c] = existing[c] ?? await folders.add(c);
  }

  // 목록은 최신순이므로, 묶음의 첫 원고가 맨 위에 오도록 시간을 거꾸로 매긴다.
  final base = DateTime.now();
  for (var i = 0; i < newsLibrary.length; i++) {
    final n = newsLibrary[i];
    await scripts.add(Script(
      title: n.title,
      body: n.body,
      category: n.category,
      difficulty: n.level,
      folderId: folderIds[n.category],
      createdAt: base.subtract(Duration(seconds: i)),
    ));
  }
  await db.insert('settings', {'key': _seededKey, 'value': '1'},
      conflictAlgorithm: ConflictAlgorithm.replace);
}
